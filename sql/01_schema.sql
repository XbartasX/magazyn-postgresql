
-- System magazynowy oparty na PostgreSQL.
-- Skrypt tworzy tabele i relacje potrzebne do obsługi
-- produktów, dostaw, wydań oraz stanów magazynowych.

CREATE SCHEMA IF NOT EXISTS magazyn_demo;

-- Kategorie pozwalają grupować produkty według ich rodzaju.
CREATE TABLE magazyn_demo.kategorie (
    kategoria_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(100) NOT NULL UNIQUE
);

-- Dane dostawców, od których zamawiany jest towar.
CREATE TABLE magazyn_demo.dostawcy (
    dostawca_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(160) NOT NULL,
    email VARCHAR(160) UNIQUE,
    telefon VARCHAR(30)
);

-- Podstawowe informacje o produktach dostępnych w magazynie.
CREATE TABLE magazyn_demo.produkty (
    produkt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kategoria_id BIGINT NOT NULL,
    sku VARCHAR(40) NOT NULL UNIQUE,
    nazwa VARCHAR(160) NOT NULL,
    cena_netto NUMERIC(12, 2) NOT NULL CHECK (cena_netto >= 0),
    stan_minimalny INTEGER NOT NULL DEFAULT 0 CHECK (stan_minimalny >= 0),
    aktywny BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_produkty_kategorie
        FOREIGN KEY (kategoria_id)
        REFERENCES magazyn_demo.kategorie(kategoria_id)
);

-- Indeks przyspiesza wyszukiwanie produktów według kategorii.
CREATE INDEX idx_produkty_kategoria
    ON magazyn_demo.produkty(kategoria_id);

-- Aktualny stan każdego produktu i data ostatniej aktualizacji.
CREATE TABLE magazyn_demo.stany_magazynowe (
    produkt_id BIGINT PRIMARY KEY,
    ilosc INTEGER NOT NULL DEFAULT 0 CHECK (ilosc >= 0),
    zaktualizowano TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stany_produkt
        FOREIGN KEY (produkt_id)
        REFERENCES magazyn_demo.produkty(produkt_id)
        ON DELETE CASCADE
);

-- Dokumenty przyjęcia rejestrują dostawy od dostawców.
CREATE TABLE magazyn_demo.dokumenty_przyjecia (
    przyjecie_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dostawca_id BIGINT NOT NULL,
    data_przyjecia TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'roboczy'
        CHECK (status IN ('roboczy', 'zatwierdzony')),

    CONSTRAINT fk_przyjecia_dostawca
        FOREIGN KEY (dostawca_id)
        REFERENCES magazyn_demo.dostawcy(dostawca_id)
);

CREATE INDEX idx_przyjecia_data
    ON magazyn_demo.dokumenty_przyjecia(data_przyjecia);

-- Pozycje określają produkty, ilości i ceny zakupu w dostawie.
CREATE TABLE magazyn_demo.pozycje_przyjecia (
    przyjecie_id BIGINT NOT NULL,
    produkt_id BIGINT NOT NULL,
    ilosc INTEGER NOT NULL CHECK (ilosc > 0),
    cena_zakupu NUMERIC(12, 2) NOT NULL CHECK (cena_zakupu >= 0),

    PRIMARY KEY (przyjecie_id, produkt_id),

    CONSTRAINT fk_pozycje_przyjecia_dokument
        FOREIGN KEY (przyjecie_id)
        REFERENCES magazyn_demo.dokumenty_przyjecia(przyjecie_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_pozycje_przyjecia_produkt
        FOREIGN KEY (produkt_id)
        REFERENCES magazyn_demo.produkty(produkt_id)
);

-- Dokumenty wydania rejestrują przekazanie towaru odbiorcom.
CREATE TABLE magazyn_demo.dokumenty_wydania (
    wydanie_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    odbiorca VARCHAR(160) NOT NULL,
    data_wydania TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'roboczy'
        CHECK (status IN ('roboczy', 'zatwierdzony'))
);

CREATE INDEX idx_wydania_data
    ON magazyn_demo.dokumenty_wydania(data_wydania);

-- Pozycje określają produkty i ilości wydawane odbiorcy.
CREATE TABLE magazyn_demo.pozycje_wydania (
    wydanie_id BIGINT NOT NULL,
    produkt_id BIGINT NOT NULL,
    ilosc INTEGER NOT NULL CHECK (ilosc > 0),

    PRIMARY KEY (wydanie_id, produkt_id),

    CONSTRAINT fk_pozycje_wydania_dokument
        FOREIGN KEY (wydanie_id)
        REFERENCES magazyn_demo.dokumenty_wydania(wydanie_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_pozycje_wydania_produkt
        FOREIGN KEY (produkt_id)
        REFERENCES magazyn_demo.produkty(produkt_id)
);

-- Indeks ułatwia wyszukiwanie wydań zawierających dany produkt.
CREATE INDEX idx_pozycje_wydania_produkt
    ON magazyn_demo.pozycje_wydania(produkt_id);
